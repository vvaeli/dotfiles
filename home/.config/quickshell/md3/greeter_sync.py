#!/usr/bin/env python3
"""Bring the login screen (ReGreet) in line with the desktop: palette, wallpaper, avatar.

Writes into /etc/greetd/md3, which belongs to the user (the greeter only reads it):
colors.css from the md3 palette, the wallpaper framed by the shell's bar and frame, a round
avatar with the user's initial (or ~/.face), plus style.css and regreet.toml from greeter/.
Does nothing when the directory is not writable.
"""
import json
import os
from pathlib import Path
import shutil
import sys
import tempfile

HOME = Path.home()
BASE = Path(__file__).resolve().parent
STATE = Path(os.environ.get('XDG_STATE_HOME', HOME / '.local/state')) / 'md3'
TARGET = Path(sys.argv[1]) if len(sys.argv) > 1 else Path('/etc/greetd/md3')
FONT = '/usr/share/fonts/Adwaita/AdwaitaSans-Regular.ttf'


def atomic(path, write):
    with tempfile.NamedTemporaryFile(dir=path.parent, delete=False, suffix=path.suffix) as handle:
        temporary = Path(handle.name)
    try:
        write(temporary)
        temporary.chmod(0o644)
        temporary.replace(path)
    finally:
        temporary.unlink(missing_ok=True)


def colors():
    try: palette = json.loads((STATE / 'colors.json').read_text())
    except (OSError, ValueError): palette = {}
    names = {'surface': 'surface', 'card': 'cardSurface', 'button': 'buttonSurface', 'hover': 'cardHover',
             'primary': 'primary', 'on_primary': 'textPrimary', 'primary_container': 'primaryContainer',
             'on_primary_container': 'textPrimaryContainer', 'secondary_container': 'secondaryContainer',
             'text': 'textSurface', 'muted': 'muted', 'outline': 'outline', 'error': 'error'}
    defaults = {'surface': '#121318', 'cardSurface': '#1a1b21', 'buttonSurface': '#292a2f', 'cardHover': '#34343a',
                'primary': '#b4c5ff', 'textPrimary': '#1a2d60', 'primaryContainer': '#324478',
                'textPrimaryContainer': '#dbe1ff', 'secondaryContainer': '#414659', 'textSurface': '#e3e2e9',
                'muted': '#c5c6d0', 'outline': '#45464f', 'error': '#ffb4ab'}
    lines = ['/* Generated by greeter_sync.py from the md3 palette. */']
    for css, key in names.items():
        lines.append(f'@define-color md3_{css} {palette.get(key, defaults[key])};')
    return '\n'.join(lines) + '\n', {key: palette.get(key, value) for key, value in defaults.items()}


# The greeter shows on DP-1 only (see launch-regreet); the image matches it pixel for pixel.
SCREEN = (2560, 1440)
# Same geometry as the shell: Theme.barHeight, frameWidth, frameRadius, menuJoinRadius.
BAR, FRAME, FRAME_RADIUS, JOIN = 44, 6, 25, 24
# Surface under the power buttons, grown from the bottom frame like the dock.
DOCK = (168, 60)


def background(palette, wallpaper, out):
    """The desktop as the shell draws it: the blurred wallpaper inside the bar and screen frame,
    with the frame's soft inner shadow, and a dock-like surface for the power buttons."""
    from PIL import Image, ImageDraw, ImageEnhance, ImageFilter, ImageOps
    width, height = SCREEN
    if wallpaper and wallpaper.is_file():
        image = ImageOps.fit(Image.open(wallpaper).convert('RGB'), SCREEN, Image.LANCZOS)
        image = image.filter(ImageFilter.GaussianBlur(24))
        image = ImageEnhance.Brightness(image).enhance(0.8)
    else:
        image = Image.new('RGB', SCREEN, palette['cardSurface'])
    mask = Image.new('L', SCREEN, 255)
    draw = ImageDraw.Draw(mask)
    draw.rounded_rectangle((FRAME, BAR, width - FRAME - 1, height - FRAME - 1), FRAME_RADIUS, fill=0)
    # Dock: rounded top corners, reverse curves flowing into the bottom frame.
    dock_w, dock_h = DOCK
    left, right = (width - dock_w) // 2, (width + dock_w) // 2
    bottom = height - FRAME
    top = bottom - dock_h
    draw.rounded_rectangle((left, top, right, bottom + 40), 28, fill=255)
    for corner in (left - JOIN, right):
        draw.rectangle((corner, bottom - JOIN, corner + JOIN, bottom), fill=255)
    draw.ellipse((left - 2 * JOIN, bottom - 2 * JOIN, left, bottom), fill=0)
    draw.ellipse((right, bottom - 2 * JOIN, right + 2 * JOIN, bottom), fill=0)
    draw.rounded_rectangle((left, top, right, bottom + 40), 28, fill=255)
    shadow = mask.filter(ImageFilter.GaussianBlur(14)).point(lambda v: int(v * 0.45))
    image = Image.composite(Image.new('RGB', SCREEN, 'black'), image, shadow)
    image = Image.composite(Image.new('RGB', SCREEN, palette['surface']), image, mask)
    image.save(out, 'PNG')


def avatar(palette, out):
    from PIL import Image, ImageDraw, ImageFont
    size = 384
    face = HOME / '.face'
    mask = Image.new('L', (size, size), 0)
    ImageDraw.Draw(mask).ellipse((0, 0, size - 1, size - 1), fill=255)
    if face.is_file():
        picture = Image.open(face).convert('RGB')
        side = min(picture.size)
        picture = picture.crop(((picture.width - side) // 2, (picture.height - side) // 2,
                                (picture.width + side) // 2, (picture.height + side) // 2)).resize((size, size))
    else:
        picture = Image.new('RGB', (size, size), palette['primaryContainer'])
        draw = ImageDraw.Draw(picture)
        font = ImageFont.truetype(FONT, 170)
        font.set_variation_by_axes([600]) if hasattr(font, 'set_variation_by_axes') else None
        letter = (os.environ.get('USER') or 'u')[0].upper()
        draw.text((size / 2, size / 2 + 4), letter, font=font, fill=palette['textPrimaryContainer'], anchor='mm')
    result = Image.new('RGBA', (size, size))
    result.paste(picture, (0, 0), mask)
    result.save(out, 'PNG')


def main():
    if not TARGET.is_dir() or not os.access(TARGET, os.W_OK):
        print(f'{TARGET} is not writable; login screen not updated', file=sys.stderr)
        return
    css, palette = colors()
    atomic(TARGET / 'colors.css', lambda p: p.write_text(css))
    for name in ('style.css', 'regreet.toml'):
        atomic(TARGET / name, lambda p, name=name: shutil.copyfile(BASE / 'greeter' / name, p))
    try:
        selected = json.loads((STATE / 'wallpaper.json').read_text())
        wallpaper = Path(selected['preview'] if selected.get('video') else selected['path'])
    except (OSError, ValueError, KeyError):
        wallpaper = None
    atomic(TARGET / 'background.png', lambda p: background(palette, wallpaper, p))
    (TARGET / 'background.jpg').unlink(missing_ok=True)
    atomic(TARGET / 'avatar.png', lambda p: avatar(palette, p))


if __name__ == '__main__':
    main()
