// Regenerates src/webkit-recolor.css: the store and community stylesheets rewritten to the md3 palette.
// Steam's web pages load their CSS from a CDN that cannot be read from inside the page, so md3.js
// cannot recolor them at runtime like the client windows. This script loads the pages in a headless
// Chrome (started with --remote-debugging-port=9333), downloads every stylesheet, runs the same
// conversion as md3.js and writes the result.
//   google-chrome-stable --headless=new --remote-debugging-port=9333 --user-data-dir=/tmp/md3-gen about:blank &
//   node tools/gen-webkit.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const pages = process.argv.slice(2).length ? process.argv.slice(2) : [
    'https://store.steampowered.com/',
    'https://store.steampowered.com/app/730/',
    'https://store.steampowered.com/search/?term=portal',
    'https://steamcommunity.com/id/gabelogannewell',
    'https://steamcommunity.com/app/730',
];
const port = process.env.CDP_PORT || 9333;
const target = (await (await fetch(`http://localhost:${port}/json/list`)).json()).find(t => t.type === 'page');
const ws = new WebSocket(target.webSocketDebuggerUrl);
let id = 0; const pending = new Map();
ws.onmessage = e => { const m = JSON.parse(e.data); if (pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id); } };
await new Promise(r => ws.onopen = r);
const call = (method, params = {}) => new Promise(r => { pending.set(++id, r); ws.send(JSON.stringify({ id, method, params })); });
const evaluate = async expression => (await call('Runtime.evaluate', { expression, awaitPromise: true, returnByValue: true })).result?.result?.value;
await call('Page.enable');

const recolor = readFileSync(path.join(root, 'src/md3.js'), 'utf8');
const seen = new Set();
let output = '';
for (const url of pages) {
    await call('Page.navigate', { url });
    await new Promise(r => setTimeout(r, 7000));
    const hrefs = await evaluate(`[...document.styleSheets].map(s => s.href).filter(Boolean)`) || [];
    const inline = await evaluate(`(() => { ${recolor}; return [...document.styleSheets].filter(s => !s.href).map(s => { try { return window.__md3Recolor.convert(s.cssRules); } catch { return ''; } }).join(''); })()`) || '';
    if (inline && !seen.has(inline)) { seen.add(inline); output += `/* inline styles of ${url} */\n${inline}\n`; }
    for (const href of hrefs) {
        const key = href.replace(/\?.*/, '');
        if (seen.has(key)) continue;
        seen.add(key);
        let text;
        try { text = await (await fetch(href)).text(); } catch { continue; }
        // Font files and @import are not needed for colors; constructable sheets reject @import.
        text = text.replace(/@import[^;]+;/g, '');
        const css = await evaluate(`(() => { ${recolor}; const sheet = new CSSStyleSheet(); sheet.replaceSync(${JSON.stringify(text)}); return window.__md3Recolor.convert(sheet.cssRules); })()`);
        if (css) output += `/* ${key} */\n${css}\n`;
    }
    console.log(url, '->', output.length, 'bytes');
}
writeFileSync(path.join(root, 'src/webkit-recolor.css'),
    '/* Generated by tools/gen-webkit.mjs: Steam store and community colors mapped to the md3 palette. */\n' + output);
ws.close();
process.exit(0);
